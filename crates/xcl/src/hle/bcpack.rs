//! Bounded BC7 BCPack entropy layer. This does not reconstruct BC7 blocks.
//! Alphabet entries are the symbol width minus one. Two symbols per lane are
//! produced for each BC7 block; all 16 lanes share an eight-byte-per-clock feeder.

use std::fmt;

pub const BC7_ALPHABET_BITS: [u8; 16] = [3, 3, 7, 7, 7, 7, 7, 6, 6, 4, 5, 7, 7, 7, 7, 4];
pub const MAX_INPUT_BYTES: usize = 16 << 20;
pub const MAX_OUTPUT_SYMBOLS: usize = 16 << 20;
const LOWER: u32 = 1 << 24;
const MAX_CYCLES: usize = 64_000_000;

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DecodeError {
    Bounds,
    Allocation,
    InvalidAlphabet { lane: usize },
    InvalidHeader { lane: usize },
    InvalidSymbol { lane: usize },
    InvalidEndState { lane: usize },
    Truncated { consumed: usize },
    TrailingData { consumed: usize },
    CycleLimit,
}

impl fmt::Display for DecodeError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "BCPack entropy decode: {self:?}")
    }
}
impl std::error::Error for DecodeError {}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Phase { Idle, Header0, Header1, Header2, Process, Drain }

struct Lane {
    alphabet: u8,
    phase: Phase,
    input: Option<u8>,
    symbol: Option<u8>,
    input_remaining: u32,
    output_remaining: usize,
    p0: u32,
    p1: u32,
    long_header: bool,
    flush: bool,
    q: usize,
    eab: usize,
    virtual_zeros: u8,
    done: bool,
    start: bool,
    stalled: bool,
    final_state: u32,
}

impl Lane {
    fn need_byte(&self) -> bool {
        self.input.is_none() && match self.phase {
            Phase::Header0 | Phase::Header1 | Phase::Header2 => true,
            Phase::Process => self.input_remaining > 0,
            _ => false,
        }
    }

    fn inverse(&self, cf: u16) -> u16 {
        let mut seg = 0usize;
        for k in (1..self.eab + 2).rev() {
            if cf >= tables::BASE_TABLE[self.eab][self.q][k] {
                seg = k;
                break;
            }
        }
        let base = if seg == 0 { 0 } else { 1u32 << (seg - 1) };
        let dist = u32::from(cf).wrapping_sub(u32::from(tables::BASE_TABLE[self.eab][self.q][seg]))
            .wrapping_add(u32::from(tables::RN_TABLE[self.eab][self.q][seg])) & 0xFFFF;
        let steps = ((dist.wrapping_mul(tables::RF_TABLE[self.eab][self.q][seg]) >> 15)
            >> tables::RS_TABLE[self.eab][self.q][seg]) & 0x1FF;
        ((base + steps) & 0x1FF) as u16
    }

    fn advance(&self, state: u32, symbol: u8) -> u32 {
        let symbol = u32::from(symbol);
        let seg = (32 - symbol.leading_zeros()) as usize;
        let start = if seg == 0 { 0 } else { 1 << (seg - 1) };
        let freq = u32::from(tables::FREQ_TABLE[self.eab][self.q][seg]);
        let cumulative = (u32::from(tables::BASE_TABLE[self.eab][self.q][seg])
            .wrapping_add(freq.wrapping_mul(symbol - start))) & 0xFFFF;
        let (freq, cumulative) = if cumulative == 0 { (freq.wrapping_sub(1) & 0xFFFF, 1) } else { (freq, cumulative) };
        freq.wrapping_mul(state >> 16).wrapping_add(state & 0xFFFF).wrapping_sub(cumulative)
    }

    fn step(&mut self, lane: usize) -> Result<(), DecodeError> {
        match self.phase {
            Phase::Idle => {
                if self.start { self.start = false; self.phase = Phase::Header0; }
            }
            Phase::Header0 => if let Some(byte) = self.input.take() {
                self.input_remaining = 0;
                self.phase = Phase::Header1;
                self.virtual_zeros = 0;
                self.q = usize::from(byte & 15);
                self.long_header = byte & 0x20 != 0;
                self.flush = byte & 0x10 != 0;
                let eab = (i32::from(self.alphabet) - i32::from(byte >> 6)) & 15;
                if eab > 8 { return Err(DecodeError::InvalidHeader { lane }); }
                self.eab = eab as usize;
            },
            Phase::Header1 => if let Some(byte) = self.input.take() {
                self.input_remaining = u32::from(byte);
                self.phase = if self.long_header { Phase::Header2 } else {
                    self.input_remaining += 1;
                    Phase::Process
                };
            },
            Phase::Header2 => if let Some(byte) = self.input.take() {
                self.input_remaining = ((u32::from(byte) << 8) | (self.input_remaining & 0xFF)) + 257;
                self.phase = Phase::Process;
            },
            Phase::Process | Phase::Drain => {
                let consume = self.phase == Phase::Process && self.p0 < LOWER && self.input_remaining > 0 && self.input.is_some();
                let mut state = if consume { ((self.p0 & 0xFF_FFFF) << 8) | u32::from(self.input.unwrap()) } else { self.p0 };
                let remaining = self.input_remaining - u32::from(consume);
                // Restore only omitted low zero bytes, after this fragment's physical
                // byte budget is exhausted. Never borrow bytes from the next fragment.
                if self.flush && remaining == 0 {
                    while state > 0 && state < LOWER && self.virtual_zeros < 2 {
                        state <<= 8;
                        self.virtual_zeros += 1;
                    }
                }
                let produce = state > LOWER && self.output_remaining > 0;
                self.p1 = state;
                if produce {
                    let symbol = self.inverse(state as u16);
                    if symbol > u8::MAX as u16 || u32::from(symbol) >= (1u32 << (self.eab + 1)) {
                        return Err(DecodeError::InvalidSymbol { lane });
                    }
                    self.output_remaining -= 1;
                    self.symbol = Some(symbol as u8);
                } else { self.symbol = None; }
                if self.phase == Phase::Process {
                    if consume { self.input_remaining -= 1; self.input = None; }
                    if self.input_remaining == 0 {
                        if self.output_remaining > 0 {
                            if state == LOWER {
                                self.phase = Phase::Header0;
                                if self.flush { self.p1 = 0; }
                            } else { self.phase = Phase::Drain; }
                        } else { self.finish(state); }
                    }
                } else if state <= LOWER {
                    if self.output_remaining > 0 {
                        if self.flush && state != LOWER { return Err(DecodeError::InvalidEndState { lane }); }
                        self.phase = Phase::Header0;
                        if self.flush { self.p0 = 0; self.p1 = 0; }
                    } else { self.finish(state); }
                }
            }
        }
        Ok(())
    }

    fn finish(&mut self, state: u32) {
        self.done = true;
        self.phase = Phase::Idle;
        self.final_state = self.symbol.map_or(state, |s| self.advance(state, s));
    }
}

pub fn decode_bc7_entropy(data: &[u8], block_count: usize) -> Result<[Vec<u8>; 16], DecodeError> {
    let target = block_count.checked_mul(2).ok_or(DecodeError::Bounds)?;
    decode_entropy(data, BC7_ALPHABET_BITS, target)
}

/// Decode exactly `target` byte symbols from each of 1..=16 lanes. Lane alphabet
/// entries must be 0..=7; this byte API deliberately does not accept 9-bit symbols.
pub fn decode_entropy<const N: usize>(data: &[u8], alphabet_bits: [u8; N], target: usize) -> Result<[Vec<u8>; N], DecodeError> {
    let total = target.checked_mul(N).filter(|&n| n <= MAX_OUTPUT_SYMBOLS).ok_or(DecodeError::Bounds)?;
    if N == 0 || N > 16 || target == 0 || data.is_empty() || data.len() > MAX_INPUT_BYTES { return Err(DecodeError::Bounds); }
    if let Some(lane) = alphabet_bits.iter().position(|&bits| bits > 7) { return Err(DecodeError::InvalidAlphabet { lane }); }
    let mut output: [Vec<u8>; N] = std::array::from_fn(|_| Vec::new());
    for symbols in &mut output { symbols.try_reserve_exact(target).map_err(|_| DecodeError::Allocation)?; }
    let mut lanes: [Lane; N] = std::array::from_fn(|lane| Lane {
        alphabet: alphabet_bits[lane], phase: Phase::Idle, input: None, symbol: None,
        input_remaining: 0, output_remaining: target, p0: 0, p1: 0, long_header: false,
        flush: false, q: 0, eab: 0, virtual_zeros: 0, done: false, start: true,
        stalled: false, final_state: 0,
    });
    let max_cycles = total.checked_add(data.len()).and_then(|n| n.checked_mul(64)).and_then(|n| n.checked_add(1000))
        .ok_or(DecodeError::Bounds)?.min(MAX_CYCLES);
    let (mut slots, mut pos, mut emitted) = (0u16, 0usize, 0usize);
    let (mut last_progress, mut last_change) = (None, 0usize);
    for cycle in 0..max_cycles {
        let mut served = 0;
        for (i, lane) in lanes.iter_mut().enumerate() {
            let blocked = lane.symbol.is_some() && slots & (1 << i) != 0;
            let need = lane.need_byte();
            let valid = need && !blocked && served < 8 && pos < data.len();
            lane.stalled = (need && !valid) || blocked;
            if lane.stalled { continue; }
            if matches!(lane.phase, Phase::Process | Phase::Drain) {
                lane.p0 = lane.symbol.map_or(lane.p1, |s| lane.advance(lane.p1, s));
            }
            if valid { lane.input = Some(data[pos]); pos += 1; served += 1; }
            if let Some(symbol) = lane.symbol.take() {
                if output[i].len() >= target { return Err(DecodeError::InvalidSymbol { lane: i }); }
                output[i].push(symbol); emitted += 1; slots |= 1 << i;
            }
        }
        let (mut active, mut finished, mut state_sum) = (0u16, true, 0u32);
        for (i, lane) in lanes.iter_mut().enumerate() {
            if !lane.stalled { lane.step(i)?; }
            if !(lane.done && lane.symbol.is_none() && slots & (1 << i) == 0) { active |= 1 << i; }
            finished &= lane.done && lane.symbol.is_none();
            state_sum += lane.phase as u32;
        }
        if slots != 0 && slots & active == active { slots = 0; }
        if finished {
            for (i, lane) in lanes.iter().enumerate() {
                if output[i].len() != target || !matches!(lane.final_state, LOWER | 0x1_0000 | 0x100) {
                    return Err(DecodeError::InvalidEndState { lane: i });
                }
            }
            if data[pos..].iter().any(|&b| b != 0) { return Err(DecodeError::TrailingData { consumed: pos }); }
            return Ok(output);
        }
        let progress = (pos, emitted, state_sum);
        if last_progress != Some(progress) { last_progress = Some(progress); last_change = cycle; }
        else if cycle - last_change > 64 { return Err(DecodeError::Truncated { consumed: pos }); }
    }
    Err(DecodeError::CycleLimit)
}

